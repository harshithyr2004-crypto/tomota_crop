class TranslationService:
    @staticmethod
    def get_supported_languages() -> Dict[str, str]:
        return LANGUAGES

    @staticmethod
    def translate(text: str, target_lang: str) -> str:
        if not target_lang or target_lang == "en":
            return text
        
        # Check dictionary exact match
        if text in TRANSLATION_DICTIONARY:
            return TRANSLATION_DICTIONARY[text].get(target_lang, text)
        
        # Fallback dictionary key substring lookup
        for key, trans in TRANSLATION_DICTIONARY.items():
            if key.lower() == text.lower().strip():
                return trans.get(target_lang, text)
                
        return text

translation_service_instance = TranslationService()
